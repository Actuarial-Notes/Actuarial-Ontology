#!/usr/bin/env python3
"""Writes lists/lists.json, the controlled lists in a form any script can read.

    python3 tools/export_lists.py            # rewrite lists/lists.json
    python3 tools/export_lists.py --check    # exit 1 if the file is out of date

The Turtle files in lists/ are the source. The JSON is generated from them
for consumers that have no RDF library; the Actuarial Notes Wiki's lint
scripts read a copy of it. Each list is keyed by the local name of its
class (or, for a SKOS scheme, of the scheme), and each entry gives:

    id          the term's local name; its IRI is `namespace` + id
    label       its English label
    notations   every spelling a record may use for it: the ISO code of a
                jurisdiction, then each skos:notation
    altLabels   synonyms (skos:altLabel)
    broader     the id of the entry it is part of, if any
    definition  what it means, where the list says

Run from the repo root.
"""
import glob
import json
import sys

from rdflib import OWL, RDF, RDFS, Graph, Namespace, URIRef
from rdflib.namespace import SKOS

AO = Namespace("http://actuarialnotes.com/ontology/actuarial#")
OUT = "lists/lists.json"
BROADER = (AO.partOfJurisdiction, AO.broaderLine, SKOS.broader)
# A record's spelling must pick out one entry of these lists. (A quantity
# kind's notation is the wiki's coarser `Kind`, which several kinds share.)
ONE_ENTRY_PER_NOTATION = ("Jurisdiction", "LineOfBusiness", "Unit", "DocumentType", "FactCheckStatus",
                          "RegulatoryDomain", "RoleType")


def local(term):
    return str(term)[len(str(AO)):]


def build():
    lists = Graph()
    for path in sorted(glob.glob("lists/*.ttl")):
        lists.parse(path)
    core = Graph().parse("ontology/core.ttl")
    version = str(next(core.objects(None, OWL.versionInfo)))

    groups = {}
    for subject in sorted(set(lists.subjects()), key=str):
        if not isinstance(subject, URIRef) or not str(subject).startswith(str(AO)):
            continue
        scheme = lists.value(subject, SKOS.inScheme)
        kinds = [scheme] if scheme else sorted(lists.objects(subject, RDF.type), key=str)
        label = lists.value(subject, SKOS.prefLabel) or lists.value(subject, RDFS.label)
        entry = {"id": local(subject), "label": str(label)}
        iso = lists.value(subject, AO.isoCode)
        notations = ([str(iso)] if iso else []) + sorted(str(n) for n in lists.objects(subject, SKOS.notation))
        entry["notations"] = notations
        alt = sorted(str(a) for a in lists.objects(subject, SKOS.altLabel))
        if alt:
            entry["altLabels"] = alt
        for prop in BROADER:
            parent = lists.value(subject, prop)
            if parent is not None:
                entry["broader"] = local(parent)
        definition = lists.value(subject, SKOS.definition) or lists.value(subject, RDFS.comment)
        if definition:
            entry["definition"] = str(definition)
        for kind in kinds:
            if str(kind).startswith(str(AO)):
                groups.setdefault(local(kind), []).append(entry)

    errors = []
    for key in ONE_ENTRY_PER_NOTATION:
        seen = {}
        for entry in groups.get(key, []):
            for notation in entry["notations"]:
                if notation in seen:
                    errors.append(f"{key}: notation {notation!r} is on both {seen[notation]} and {entry['id']}")
                seen[notation] = entry["id"]
    document = {
        "about": "The Actuarial Ontology's controlled lists. Generated by tools/export_lists.py from lists/*.ttl; do not edit.",
        "namespace": str(AO),
        "version": version,
        "lists": {key: groups[key] for key in sorted(groups)},
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n", errors


def main():
    text, errors = build()
    for e in errors:
        print("ERROR:", e)
    if "--check" in sys.argv:
        try:
            current = open(OUT, encoding="utf8").read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print(f"ERROR: {OUT} is out of date; run python3 tools/export_lists.py")
            errors.append("stale")
    else:
        open(OUT, "w", encoding="utf8").write(text)
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
